export const SCENE_LIST = ORDER.map(([key, code, name], i) => ({
  no: i + 1, code, name, key,
}));

/** 状態から場面を引く。未登録なら no=0 で返す（見落としに気づけるように） */
export function sceneOf(s) {
  const key = s.step === 'ending' ? `ending@${s.ending}` : `${s.step}@${s.room}`;
  return BY_KEY.get(key) ?? { no: 0, code: '??', name: `未登録: ${key}` };
}
