/**
 * マゼンタ抜きの判定（設計書 §5.4）
 *
 * ★実行時（render/chromaKey.js）と検査（scripts/check-assets.mjs）は
 * 必ずここを使う。別々に持っていたせいで、
 *
 *   実行時 : min(r, b) - g >= 100      → 抜ける
 *   検査   : g < 60 かつ r,b が 255 付近 → 「マゼンタ背景がない」
 *
 * と食い違い、**実際には綺麗に抜ける絵を「抜けない」と誤って報告した**。
 * 生成AIの出すマゼンタは (253, 77, 251) のように緑が残るので、
 * 緑の絶対値で切ると落ちる。三原色の関係で見るのが正しい。
 *
 * three を import しないこと。Node のスクリプトからも読む。
 */

/** マゼンタらしさ。完全なマゼンタ(255,0,255)なら 255 */
export const magentaness = (r, g, b) => Math.min(r, b) - g;

/**
 * JPEG で出てくると境界が滲んで紫の縁が残るので、
 * 硬く切らずに二段の閾値で羽を付け、縁のマゼンタも抜く。
 */
export const KEY_HI = 100;   // これ以上は完全に透明
export const KEY_LO = 34;    // これ以上は部分的に透明にして色も抜く

/** 完全に透明になる画素か */
export const isKeyed = (r, g, b) => magentaness(r, g, b) >= KEY_HI;
