/**
 * 相方の台詞テーブル（仕様書 §11.1）
 *
 * 役割は「疑問の提示」のみ。正解は絶対に言わない（仕様書 §0.1-5）。
 * P が 0 になって折れたあとは沈黙する。
 */

/**
 * P の値から段階（0〜4）を返す。4 が元気、0 が折れた状態。
 *
 * ★閾値は実際に取りうる P の値に合わせる。
 * P は 8 から始まり、判断室ごとに 2 減って 8→6→4→2→0 を辿るので、
 * この5段階がちょうど1部屋ずつ対応する。
 * 以前は段階4の閾値が 9 だったため、初期値 8 では段階4に一度も入らず、
 * 「妙だぞ、この店」という最初の台詞が誰にも見られなかった。
 */
export function partnerStage(P) {
  if (P >= 8) return 4;
  if (P >= 6) return 3;
  if (P >= 4) return 2;
  if (P >= 2) return 1;
  return 0;
}

